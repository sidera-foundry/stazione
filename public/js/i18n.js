const KEY = 'stazione.lang';
function pick() {
  try { const v = localStorage.getItem(KEY); if (v === 'en' || v === 'it') return v; } catch { /* not remembered */ }
  return /^it\b/i.test(globalThis.navigator?.language || '') ? 'it' : 'en';
}
export const lang = pick();
export const locale = lang === 'it' ? 'it-IT' : 'en-GB';
const dict = lang === 'it' ? IT : {};
/** Translations a module brings in its module.json ({ "it": { "English text": "Testo italiano" } }); the core's own win. */
export function addTranslations(translations) {
  const extra = translations?.[lang];
  if (!extra || typeof extra !== 'object') return;
  for (const [k, v] of Object.entries(extra)) if (typeof v === 'string' && !(k in dict)) dict[k] = v;
}

/** __('Text'), __('Text {0}', x) or the tag __`Text ${x}`: the text in the chosen language, placeholders filled. */
export function __(s, ...v) {
  const key = Array.isArray(s) ? s.reduce((a, x, i) => `${a}{${i - 1}}${x}`) : String(s);
  const out = dict[key] ?? key;
  return v.length ? out.replace(/\{(\d+)\}/g, (m, i) => (i < v.length ? String(v[i]) : m)) : out;
}
globalThis.__ = __; // for restyle.js, a classic script

/** Static text of the page: text nodes and the readable attributes, matched whole (spaces around kept). */
function translatePage() {
  document.title = dict[document.title] ?? document.title;
  const walk = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  for (let n = walk.nextNode(); n; n = walk.nextNode()) {
    const m = /^(\s*)([\s\S]*?)(\s*)$/.exec(n.data), k = m[2].replace(/\s+/g, ' ');
    if (dict[k]) n.data = m[1] + dict[k] + m[3];
  }
  for (const a of ['placeholder', 'title', 'aria-label', 'alt']) {
    for (const e of document.body.querySelectorAll(`[${a}]`)) { const t = dict[e.getAttribute(a)]; if (t) e.setAttribute(a, t); }
  }
}

/** EN/IT switch: in the header, or under the links on the sign-in pages. Reloads, so every text is drawn again. */
function mountSwitch() {
  const b = document.createElement('button');
  b.type = 'button'; b.className = 'ghost lang-btn'; b.lang = lang === 'it' ? 'en' : 'it';
  b.textContent = lang === 'it' ? 'EN' : 'IT';
  b.title = lang === 'it' ? "Lingua: italiano. Passa all'inglese" : 'Language: English. Switch to Italian';
  b.addEventListener('click', () => { try { localStorage.setItem(KEY, b.lang); location.reload(); } catch { /* storage blocked: no switch */ } });
  const bar = document.querySelector('.bar'), links = document.querySelector('main.auth .links');
  if (bar) (bar.querySelector('#logout') ? bar.querySelector('#logout').before(b) : bar.append(b));
  else if (links) links.append(b);
}

if (typeof document !== 'undefined' && document.body) {
  document.documentElement.lang = lang;
  if (lang !== 'en') translatePage();
  mountSwitch();
}
